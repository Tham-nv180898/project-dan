export function getPanelBySlug(slug: string): Panel | undefined {
  return PANELS_DATA.find((p) => p.slug === slug || p.id.toLowerCase() === slug.toLowerCase());
}

export function getAdjacentPanels(currentSlug: string): { prev?: Panel; next?: Panel } {
  const currentIndex = PANELS_DATA.findIndex(
    (p) => p.slug === currentSlug || p.id.toLowerCase() === currentSlug.toLowerCase()
  );
  if (currentIndex === -1) return {};

  return {
    prev: currentIndex > 0 ? PANELS_DATA[currentIndex - 1] : undefined,
    next: currentIndex < PANELS_DATA.length - 1 ? PANELS_DATA[currentIndex + 1] : undefined
  };
}
